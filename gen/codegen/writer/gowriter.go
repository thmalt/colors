func (w *GoWriter) pushBlock(block blockKind) {
	w.lastBlock = block
	w.blocks = append(w.blocks, block)
}

func (w *GoWriter) popBlock() blockKind {
	n := len(w.blocks)
	if n == 0 {
		panic("popState: empty state stack")
	}

	block := w.blocks[n-1]
	w.blocks = w.blocks[:n-1]

	if n -= 1; n > 0 {
		w.lastBlock = w.blocks[n-1]
	} else {
		w.lastBlock = blockNone
	}

	return block
}

func (w *GoWriter) pushBracket(bracket byte) {
	w.bracketStack = append(w.bracketStack, bracket)
}

func (w *GoWriter) popBracket() byte {
	n := len(w.bracketStack)
	if n == 0 {
		panic("popBracket: empty bracket stack")
	}

	bracket := w.bracketStack[n-1]
	w.bracketStack = w.bracketStack[:n-1]

	return bracket
}

func (w *GoWriter) Import(pkgs ...string) {
	for _, pkg := range pkgs {
		if strings.HasPrefix(pkg, "/") {
			pkg = filepath.ToSlash(filepath.Join(w.module, pkg))
		}

		w.imports = append(w.imports, pkg)
	}
}

func (w *GoWriter) begin(bracket byte) {
	w.bracket(bracket)
	w.Writeln()
	w.In()
}

func (w *GoWriter) bracket(bracket byte) {
	w.Write(bracket)
	w.pushBracket(bracket)
}

func (w *GoWriter) Begin(a ...any) {
	w.pushBlock(blockNone)

	w.LineWrite(a...)
	w.begin('{')
}

func (w *GoWriter) BeginGroup(a ...any) {
	w.pushBlock(blockNone)

	w.LineWrite(a...)
	w.begin('(')
}

func (w *GoWriter) End(a ...any) {
	w.Out()

	w.popBlock()

	switch v := w.popBracket(); v {
	case bracketBlock:
		w.Write('}')
	case bracketGroup:
		w.Write(')')
	case bracketArray:
		w.Write(']')
	default:
		panic(fmt.Errorf("unknown bracket: %v", v))
	}
	w.Writeln(a...)
}

func (w *GoWriter) Method(receiver, name string) {
	w.pushBlock(blockFuncName)

	w.LineWrite("func ", "(", receiver, ")", name)
}

func (w *GoWriter) Func(name string) {
	w.pushBlock(blockFuncName)

	w.LineWrite("func ", name)
}

func (w *GoWriter) FuncParams(params ...any) {
	if w.lastBlock != blockFuncName {
		panic(fmt.Errorf("state %s must be: %s", w.lastBlock, blockFuncName))
	}

	w.pushBlock(blockFuncSignture)

	w.Write('(')
	w.Write(params...)
	w.Write(')')
}

func (w *GoWriter) FuncResults(results ...any) {
	if w.lastBlock != blockFuncName && w.lastBlock != blockFuncSignture {
		panic(fmt.Errorf("state %s must be: %s or %s", w.lastBlock, blockFuncSignture, blockFuncName))
	}

	if w.lastBlock == blockFuncName {
		w.Write("()")
		w.pushBlock(blockFuncSignture)
	}

	s := strings.TrimSpace(fmt.Sprint(results...))
	if s == "" {
		return
	}

	if strings.ContainsAny(s, " ,") {
		w.Write('(')
		w.Write(s)
		w.Write(')')
	} else {
		w.Write(s)
	}
}

func (w *GoWriter) FuncBody() {
	if w.lastBlock != blockFuncName && w.lastBlock != blockFuncSignture {
		panic(fmt.Errorf("state %s must be: %s or %s", w.lastBlock, blockFuncSignture, blockFuncName))
	}

	switch w.lastBlock {
	case blockFuncName:
		w.Write("()")
	case blockFuncSignture:
		w.popBlock()
	}

	w.begin('{')
}

func (w *GoWriter) If(a ...any) {
	w.pushBlock(blockIf)

	w.LineWrite("if ")
	w.Write(a...)
	w.begin('{')
}

func (w *GoWriter) Else(a ...any) {
	if w.lastBlock != blockIf {
		panic(fmt.Errorf("%s must be: %s", w.lastBlock, blockIf))
	}

	w.LineWrite("} else ")
	w.Write(a...)
	w.begin('{')
}

func (w *GoWriter) ElseIf(a ...any) {
	if w.lastBlock != blockIf {
		panic(fmt.Errorf("%s must be: %s", w.lastBlock, blockIf))
	}

	w.LineWrite("} else if ")
	w.Write(a...)
	w.begin('{')
}

func (w *GoWriter) Switch(a ...any) {
	w.pushBlock(blockSwitch)

	w.LineWrite("switch ")
	w.Write(a...)
	w.begin('{')
}

func (w *GoWriter) Case(a ...any) {
	if w.lastBlock != blockSwitch {
		panic(fmt.Errorf("%s must be: %s", w.lastBlock, blockSwitch))
	}

	w.Out()
	w.LineWrite("case ")
	w.Write(a...)
	w.Writeln(':')
	w.In()
}

func (w *GoWriter) Default() {
	if w.lastBlock != blockSwitch {
		panic(fmt.Errorf("state %s must be: %s", w.lastBlock, blockSwitch))
	}

	w.Out()
	w.LineWriteln("default:")
	w.In()
}

func (w *GoWriter) Return(a ...any) {
	w.LineWrite("return ")
	w.Writeln(a...)
}

