package writer

import (
	"bytes"
	"fmt"
	"io"
	"log"
	"os"
	"path/filepath"
	"reflect"
	"runtime/debug"
	"slices"
	"strings"
	"unicode"
	"unicode/utf8"
)

type GoWriter struct {
	buf  bytes.Buffer
	temp bytes.Buffer

	imports []string

	generatorPath string
	module        string
	rootMPkg      string

	indent    int
	minIndent int

	lastBlock    blockKind
	blocks       []blockKind
	bracketStack []rune
}

func NewGoWriter() *GoWriter {
	return &GoWriter{}
}

// SubWriter creates a new [GoWriter] whose contents can be written to w using [GoWriter.Drain].
func (w *GoWriter) SubWriter() *GoWriter {
	return &GoWriter{
		indent:    w.indent,
		minIndent: w.indent,
	}
}

func (w *GoWriter) Drain(sub *GoWriter) {
	w.Write(sub.Bytes())
	sub.Reset()
}

func (w *GoWriter) Reset() {
	w.buf.Reset()

	w.imports = w.imports[:0]
	w.indent = w.minIndent
}

func (w *GoWriter) Bytes() []byte {
	return w.buf.Bytes()
}

func (w *GoWriter) SaveGoFile(filename, pkg string) {
	err := os.MkdirAll(filepath.Dir(filename), os.ModePerm)
	if err != nil {
		log.Printf("Could not create dir %s: %v", filename, err)
		return
	}
	f, err := os.Create(filename)
	if err != nil {
		log.Printf("Could not create file %s: %v", filename, err)
		return
	}
	defer f.Close()
	if _, err = w.WriteGo(f, pkg, ""); err != nil {
		log.Printf("Error writing file %s: %v", filename, err)
		return
	}
}

func (w *GoWriter) WriteGo(out io.Writer, pkg, tags string) (int, error) {
	defer w.Reset()
	fmt.Fprintf(out, "// Code generated by \"go generate %s\" in %s. DO NOT EDIT.\n\n", w.generatorPath, w.module)

	var buf bytes.Buffer

	writePkgs := func(pkgs []string) {
		for _, pkg := range pkgs {
			buf.WriteByte('\t')

			hasQuote := strings.Contains(pkg, `"`)

			if !hasQuote {
				buf.WriteByte('"')
			}

			buf.WriteString(pkg)

			if !hasQuote {
				buf.WriteByte('"')
			}

			buf.WriteByte('\n')
		}
	}

	stdlib, others := splitImports(w.imports)

	if len(stdlib) > 0 || len(others) > 0 {
		buf.WriteString("import (")
		buf.WriteByte('\n')

		writePkgs(stdlib)

		if len(stdlib) > 0 && len(others) > 0 {
			buf.WriteByte('\n')
		}

		writePkgs(others)

		buf.WriteString(")\n\n")
	}

	buf.Write(w.buf.Bytes())

	return WriteGo(out, pkg, tags, buf.Bytes())
}

func (w *GoWriter) SetGeneratedBy(module, generatorPath string) {
	w.module = module
	w.generatorPath = generatorPath
	w.rootMPkg = filepath.Base(w.module)
}

func (w *GoWriter) SetGeneratedFromType(a any) {
	info, _ := debug.ReadBuildInfo()

	t := reflect.TypeOf(a)
	if t.Kind() == reflect.Pointer {
		t = t.Elem()
	}

	pkgPath := t.PkgPath()

	w.module = ""
	for _, d := range info.Deps {
		if strings.HasPrefix(pkgPath, d.Path) {
			fmt.Println()
			w.module = d.Path
		}
	}

	w.rootMPkg = filepath.Base(w.module)
	w.generatorPath = "." + strings.TrimPrefix(pkgPath, w.module)
}

