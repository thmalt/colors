type GoWriter struct {
	buf bytes.Buffer

	imports []string

	generatorPath string
	module        string
	rootMPkg      string

	indent    int
	minIndent int

	lastBlock    blockKind
	blocks       []blockKind
	bracketStack []byte
}

type blockKind uint

const (
	blockNone blockKind = iota
	blockFuncName
	blockFuncSignture
	blockIf
	blockSwitch
)

func (s blockKind) String() string {
	switch s {
	case blockNone:
		return "blockNone"
	case blockFuncName:
		return "blockFuncName"
	case blockFuncSignture:
		return "blockFuncSignture"
	case blockIf:
		return "blockIf"
	case blockSwitch:
		return "blockSwitch"
	default:
		return fmt.Sprintf("unknown block %d", s)
	}
}

const (
	bracketBlock byte = '{'
	bracketGroup byte = '('
	bracketArray byte = '['
)

func NewGoWriter() *GoWriter {
	return &GoWriter{}
}

func WriteGo(w io.Writer, pkg, tags string, b []byte) (int, error) {
	var src []byte
	if tags != "" {
		src = append(src, tagLines(tags)...)
		src = append(src, '\n')
	}
	src = append(src, fmt.Sprintf("package %s\n", pkg)...)
	src = append(src, b...)
	formatted, err := format.Source(src)
	if err != nil {
		n, _ := w.Write(src)
		return n, err
	}
	return w.Write(formatted)
}

func tagLines(tags string) string {
	return "//go:build " + strings.ReplaceAll(tags, ",", " && ") + "\n"
}

func (w *GoWriter) Reset() {
	w.buf.Reset()
	w.imports = w.imports[:0]
	w.indent = 0
}

func (w *GoWriter) Bytes() []byte {
	return w.buf.Bytes()
}

func (w *GoWriter) NewTemp() *GoWriter {
	return &GoWriter{indent: w.indent, minIndent: w.indent}
}

func (w *GoWriter) WriteGoFile(filename, pkg string) {
	err := os.MkdirAll(filepath.Dir(filename), os.ModePerm)
	if err != nil {
		log.Printf("Could not create dir %s: %v", filename, err)
		return
	}
	f, err := os.Create(filename)
	if err != nil {
		log.Printf("Could not create file %s: %v", filename, err)
		return
	}
	defer f.Close()
	if _, err = w.WriteGo(f, pkg, ""); err != nil {
		log.Printf("Error writing file %s: %v", filename, err)
		return
	}
}

func (w *GoWriter) WriteGo(out io.Writer, pkg, tags string) (int, error) {
	defer w.Reset()
	fmt.Fprintf(out, "// Code generated by running \"go generate %s\" in %s. DO NOT EDIT.\n\n", w.generatorPath, w.module)

	var buf bytes.Buffer

	writePkgs := func(pkgs []string) {
		for _, pkg := range pkgs {
			buf.WriteString("\t")

			hasQuote := strings.Contains(pkg, "\"")

			if !hasQuote {
				buf.WriteByte('"')
			}

			buf.WriteString(pkg)

			if !hasQuote {
				buf.WriteByte('"')
			}

			buf.WriteString("\n")
		}
	}

	stdlib, others := splitImports(w.imports)

	if len(stdlib) > 0 || len(others) > 0 {
		buf.WriteString("import (\n")

		writePkgs(stdlib)

		if len(others) > 0 {
			buf.WriteString("\n")
		}

		writePkgs(others)

		buf.WriteString(")\n\n")
	}

	buf.Write(w.buf.Bytes())

	return WriteGo(out, pkg, tags, buf.Bytes())
}

func (w *GoWriter) SetGeneratedBy(module, generatorPath string) {
	w.module = module
	w.generatorPath = generatorPath
	w.rootMPkg = filepath.Base(w.module)
}

func (w *GoWriter) SetGeneratedFromType(a any) {
	info, _ := debug.ReadBuildInfo()

	t := reflect.TypeOf(a)
	if t.Kind() == reflect.Pointer {
		t = t.Elem()
	}

	pkgPath := t.PkgPath()

	w.module = ""
	for _, d := range info.Deps {
		if strings.HasPrefix(pkgPath, d.Path) {
			fmt.Println()
			w.module = d.Path
		}
	}

	w.rootMPkg = filepath.Base(w.module)
	w.generatorPath = "." + strings.TrimPrefix(pkgPath, w.module)
}

func (w *GoWriter) Module() string        { return w.module }
func (w *GoWriter) RootPackage() string   { return w.rootMPkg }
func (w *GoWriter) GeneratorPath() string { return w.generatorPath }

func (w *GoWriter) atLineStart() bool {
	b := w.buf.Bytes()
	n := len(b)
	return n == 0 || b[n-1] == '\n' || b[n-1] == '\r'
}

func (w *GoWriter) writef(format string, a ...any) {
	fmt.Fprintf(&w.buf, format, a...)
}

func (w *GoWriter) write(a ...any) {
	for _, arg := range a {
		switch v := arg.(type) {
		case string:
			w.buf.WriteString(v)
		case byte:
			w.buf.WriteByte(v)
		case rune:
			w.buf.WriteRune(v)
		case []byte:
			w.buf.Write(v)
		default:
			fmt.Fprint(&w.buf, v)
		}
	}
}

func (w *GoWriter) writeln(a ...any) {
	w.write(a...)
	w.write('\n')
}

func (w *GoWriter) writeIndent() {
	for range w.indent {
		w.write('\t')
	}
}

func (w *GoWriter) In() { w.indent++ }
func (w *GoWriter) Out() {
	if w.indent <= w.minIndent {
		panic("GoWriter.Out: negative indent")
	}

	w.indent--
}

