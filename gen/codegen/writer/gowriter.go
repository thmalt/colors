func (w *GoWriter) LineWritef(format string, a ...any) {
	if !w.atLineStart() {
		w.write('\n')
	}

	w.writeIndent()

	w.writef(format, a...)
}

func (w *GoWriter) LineWrite(a ...any) {
	if !w.atLineStart() {
		w.write('\n')
	}

	w.writeIndent()

	w.write(a...)
}

func (w *GoWriter) LineWriteln(a ...any) {
	w.LineWrite(a...)
	w.Writeln()
}

