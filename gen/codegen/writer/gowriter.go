func (w *GoWriter) pushBracket(bracket byte) {
	w.bracketStack = append(w.bracketStack, bracket)
}

func (w *GoWriter) popBracket() byte {
	n := len(w.bracketStack)
	if n == 0 {
		panic("GoWriter.End: empty bracket stack")
	}

	bracket := w.bracketStack[n-1]
	w.bracketStack = w.bracketStack[:n-1]

	return bracket
}

func (w *GoWriter) Import(pkgs ...string) {
	w.LineWrite("import (")
	w.In()
	for _, pkg := range pkgs {
		if strings.HasPrefix(pkg, "/") {
			w.LineWriteln(`"`, filepath.ToSlash(filepath.Join(w.module, pkg)), `"`)
		} else {
			w.LineWriteln(`"`, pkg, `"`)
		}
	}
	w.Out()
	w.LineWriteln(")")
	w.Writeln()
}

func (w *GoWriter) begin(bracket byte) {
	w.bracket(bracket)
	w.Writeln()
	w.In()
}

func (w *GoWriter) bracket(bracket byte) {
	w.Write(bracket)
	w.pushBracket(bracket)
}

func (w *GoWriter) Begin(a ...any) {
	w.LineWrite(a...)
	w.begin('{')
}

func (w *GoWriter) BeginGroup(a ...any) {
	w.LineWrite(a...)
	w.begin('(')
}

func (w *GoWriter) End(a ...any) {
	w.Out()

	switch v := w.popBracket(); v {
	case bracketBlock:
		w.Write('}')
	case bracketGroup:
		w.Write(')')
	case bracketArray:
		w.Write(']')
	default:
		panic(fmt.Errorf("unknown bracket: %v", v))
	}
	w.Writeln(a...)
}

func (w *GoWriter) Method(receiver, name string) {
	w.state = stateFuncName

	w.LineWrite("func ", "(", receiver, ")", name)
}

func (w *GoWriter) Func(name string) {
	w.state = stateFuncName

	w.LineWrite("func ", name)
}

func (w *GoWriter) FuncParams(params ...any) {
	if w.state != stateFuncName {
		panic(fmt.Errorf("state %s must be: %s", w.state, stateFuncName))
	}

	w.state = stateFuncParams

	w.Write('(')
	w.Write(params...)
	w.Write(')')
}

func (w *GoWriter) FuncResults(results ...any) {
	if w.state != stateFuncParams && w.state != stateFuncName {
		panic(fmt.Errorf("state %s must be: %s or %s", w.state, stateFuncParams, stateFuncName))
	}

	if w.state == stateFuncName {
		w.Write("()")
	}

	w.state = stateFuncResults

	s := strings.TrimSpace(fmt.Sprint(results...))
	if s == "" {
		return
	}

	if strings.ContainsAny(s, " ,") {
		w.Write('(')
		w.Write(s)
		w.Write(')')
	} else {
		w.Write(s)
	}
}

func (w *GoWriter) FuncBody() {
	if w.state != stateFuncResults && w.state != stateFuncParams && w.state != stateFuncName {
		panic(fmt.Errorf("state %s must be: %s or %s or %s", w.state, stateFuncResults, stateFuncParams, stateFuncName))
	}

	if w.state == stateFuncName {
		w.Write("()")
	}

	w.state = stateBlock

	w.begin('{')
}

func (w *GoWriter) If(a ...any) {
	w.state = stateIf

	w.LineWrite("if ")
	w.Write(a...)
	w.begin('{')
}

func (w *GoWriter) Else(a ...any) {
	if w.state != stateIf {
		panic(fmt.Errorf("state %s must be: %s", w.state, stateIf))
	}

	w.LineWrite("} else ")
	w.Write(a...)
	w.begin('{')
}

func (w *GoWriter) ElseIf(a ...any) {
	if w.state != stateIf {
		panic(fmt.Errorf("state %s must be: %s", w.state, stateIf))
	}

	w.LineWrite("} else if ")
	w.Write(a...)
	w.begin('{')
}

func (w *GoWriter) Switch(a ...any) {
	w.state = stateSwitch

	w.LineWrite("switch ")
	w.Write(a...)
	w.begin('{')
}

func (w *GoWriter) Case(a ...any) {
	if w.state != stateSwitch {
		panic(fmt.Errorf("state %s must be: %s", w.state, stateSwitch))
	}

	w.Out()
	w.LineWrite("case ")
	w.Write(a...)
	w.Writeln(':')
	w.In()
}

func (w *GoWriter) Default() {
	if w.state != stateSwitch {
		panic(fmt.Errorf("state %s must be: %s", w.state, stateSwitch))
	}

	w.Out()
	w.LineWriteln("default:")
	w.In()
}

func (w *GoWriter) Return(a ...any) {
	w.LineWrite("return ")
	w.Writeln(a...)
}

