func (w *GoWriter) writeIndent() {
	for range w.indent {
		w.Write('\t')
	}
}

// Returns temp []byte, until next call [GoWrite.tempBytes] or [GoWrite.tempBytesFormat]
func (w *GoWriter) tempBytes(a ...any) []byte {
	w.temp.Reset()

	appendArgs(&w.temp, a...)

	return w.temp.Bytes()
}

// Returns temp []byte, until next call [GoWrite.tempBytes] or [GoWrite.tempBytesFormat]
func (w *GoWriter) tempBytesFormat(format string, a ...any) []byte {
	w.temp.Reset()

	appendArgsFormat(&w.temp, format, a...)

	return w.temp.Bytes()
}

func (w *GoWriter) In() {
	w.indent++
}

func (w *GoWriter) Out() {
	if w.indent <= w.minIndent {
		panic("GoWriter.Out: negative indent")
	}

	w.indent--
}

func (w *GoWriter) Indent() {
	if !w.atLineStart() {
		w.Newline()
	}

	w.writeIndent()
}

func (w *GoWriter) atLineStart() bool {
	b := w.buf.Bytes()
	n := len(b)
	return n == 0 || b[n-1] == '\n' || b[n-1] == '\r'
}

func (w *GoWriter) hasTrailingSpace() bool {
	b := w.buf.Bytes()
	r, _ := utf8.DecodeLastRune(b)

	return unicode.IsSpace(r)
}

func (w *GoWriter) pushBlock(block blockKind) {
	w.lastBlock = block
	w.blocks = append(w.blocks, block)
}

func (w *GoWriter) popBlock() blockKind {
	n := len(w.blocks)
	if n == 0 {
		panic("popState: empty state stack")
	}

	block := w.blocks[n-1]
	w.blocks = w.blocks[:n-1]

	if n -= 1; n > 0 {
		w.lastBlock = w.blocks[n-1]
	} else {
		w.lastBlock = blockNone
	}

	return block
}

func (w *GoWriter) pushBracket(bracket rune) {
	w.bracketStack = append(w.bracketStack, bracket)
}

func (w *GoWriter) popBracket() rune {
	n := len(w.bracketStack)
	if n == 0 {
		panic("popBracket: empty bracket stack")
	}

	bracket := w.bracketStack[n-1]
	w.bracketStack = w.bracketStack[:n-1]

	return bracket
}

func (w *GoWriter) Import(pkgs ...string) {
	for _, pkg := range pkgs {
		if strings.HasPrefix(pkg, "/") {
			pkg = filepath.ToSlash(filepath.Join(w.module, pkg))
		}

		if !slices.Contains(w.imports, pkg) {
			w.imports = append(w.imports, pkg)
		}
	}
}

func (w *GoWriter) bracket(bracket rune) {
	w.Write(bracket)
	w.pushBracket(bracket)
}

func (w *GoWriter) openIndent(bracket rune) {
	w.bracket(bracket)
	w.Newline()

	w.In()
}

func (w *GoWriter) closeIndent() {
	w.Out()

	w.Indent()
	switch v := w.popBracket(); v {
	case bracketBlock:
		w.Write('}')
	case bracketGroup:
		w.Write(')')
	case bracketArray:
		w.Write(']')
	default:
		panic(fmt.Errorf("unknown bracket: %v", v))
	}
}

func (w *GoWriter) beginf(block blockKind, bracket rune, format string, a ...any) {
	w.pushBlock(block)

	w.LineWritef(format, a...)

	w.openIndent(bracket)
}

// Params can using []any, []any, any, ...
func (w *GoWriter) begin(block blockKind, bracket rune, a ...any) {
	w.pushBlock(block)

	w.Indent()
	for _, v := range a {
		if x, ok := v.([]any); ok {
			w.Write(x...)

			continue
		}

		w.Write(v)
	}

	w.openIndent(bracket)
}

func (w *GoWriter) End(a ...any) {
	w.popBlock()
	w.closeIndent()
	w.Writeln(a...)
}

func (w *GoWriter) Begin(a ...any) {
	w.begin(blockNone, '{', a...)
}

func (w *GoWriter) Beginf(format string, a ...any) {
	w.beginf(blockNone, '{', format, a...)
}

func (w *GoWriter) BeginGroup(a ...any) {
	w.begin(blockNone, '(', a...)
}

func (w *GoWriter) BeginGroupf(format string, a ...any) {
	w.beginf(blockNone, '(', format, a...)
}

func (w *GoWriter) Method(receiver, name string) {
	w.pushBlock(blockFuncName)

	w.LineWrite("func (", receiver, ") ", name)
}

func (w *GoWriter) Func(name string) {
	w.pushBlock(blockFuncName)

	w.LineWrite("func ", name)
}

func (w *GoWriter) FuncParams(params ...any) {
	if w.lastBlock != blockFuncName {
		panic(fmt.Errorf("state %s must be: %s", w.lastBlock, blockFuncName))
	}

	w.pushBlock(blockFuncSignture)

	w.Write('(')
	w.Write(params...)
	w.Write(')')
}

func (w *GoWriter) FuncResults(a ...any) {
	if w.lastBlock != blockFuncName && w.lastBlock != blockFuncSignture {
		panic(fmt.Errorf("state %s must be: %s or %s", w.lastBlock, blockFuncSignture, blockFuncName))
	}

	if w.lastBlock == blockFuncName {
		w.Write("()")
		w.pushBlock(blockFuncSignture)
	}

	b := bytes.TrimSpace(w.tempBytes(a...))

	if len(b) == 0 {
		return
	}

	w.Write(' ')
	if bytes.ContainsAny(b, " ,") && !bytes.ContainsAny(b, "()") {
		w.Write('(')
		w.Write(b)
		w.Write(')')
	} else {
		w.Write(b)
	}
}

func (w *GoWriter) FuncBody() {
	if w.lastBlock != blockFuncName && w.lastBlock != blockFuncSignture {
		panic(fmt.Errorf("state %s must be: %s or %s", w.lastBlock, blockFuncSignture, blockFuncName))
	}

	switch w.lastBlock {
	case blockFuncName:
		w.Write("()")
	case blockFuncSignture:
		w.popBlock()
	}

	w.Write(' ')

	w.openIndent('{')
}

func (w *GoWriter) If(a ...any) {
	w.begin(blockIf, '{', "if ", a, ' ')
}

func (w *GoWriter) ElseIf(a ...any) {
	if w.lastBlock != blockIf {
		panic(fmt.Errorf("%s must be: %s", w.lastBlock, blockIf))
	}

	w.Out()
	w.LineWrite("} else if ")
	w.Write(a...)
	if !w.hasTrailingSpace() {
		w.Write(' ')
	}
	w.openIndent('{')
}

func (w *GoWriter) Else(a ...any) {
	if w.lastBlock != blockIf {
		panic(fmt.Errorf("%s must be: %s", w.lastBlock, blockIf))
	}

	w.Out()
	w.LineWrite("} else ")
	w.Write(a...)
	if !w.hasTrailingSpace() {
		w.Write(' ')
	}
	w.openIndent('{')
}

func (w *GoWriter) Switch(a ...any) {
	w.begin(blockSwitch, '{', "switch ", a)
}

func (w *GoWriter) Case(a ...any) {
	if w.lastBlock != blockSwitch {
		panic(fmt.Errorf("%s must be: %s", w.lastBlock, blockSwitch))
	}

	w.Out()
	w.LineWrite("case ")
	w.Write(a...)
	w.Writeln(':')
	w.In()
}

func (w *GoWriter) Default() {
	if w.lastBlock != blockSwitch {
		panic(fmt.Errorf("%s must be: %s", w.lastBlock, blockSwitch))
	}

	w.Out()
	w.LineWriteln("default:")
	w.In()
}

func (w *GoWriter) Return(a ...any) {
	b := w.tempBytes(a...)
	w.LineWrite("return")

	if !isBlank(b) {
		w.Write(' ')
		w.Write(b)
	}

	w.Newline()
}

func (w *GoWriter) comment(p []byte, inline bool) {
	first := true
	lastBlank := false

	forEachLine(p, func(line []byte) bool {
		blank := isBlank(line)
		if blank && lastBlank {
			return true
		}

		if inline && first {
			if w.atLineStart() {
				w.Indent()
			} else {
				w.Write(' ')
			}
			w.Write("//")
			first = false
		} else {
			w.LineWrite("//")
		}

		if !blank {
			if !hasLeadingSpace(line) {
				w.Write(' ')
			}

			w.Writeln(line)
		}

		lastBlank = blank
		return true
	})
}

func (w *GoWriter) Comment(a ...any) {
	if len(a) == 0 {
		w.LineWrite("//")
		return
	}

	w.comment(w.tempBytes(a...), false)
}

func (w *GoWriter) Commentf(format string, a ...any) {
	w.comment(w.tempBytesFormat(format, a...), false)
}

func (w *GoWriter) InlineComment(a ...any) {
	w.comment(w.tempBytes(a...), true)
}

func (w *GoWriter) InlineCommentf(format string, a ...any) {
	w.comment(w.tempBytesFormat(format, a...), true)
}

func (w *GoWriter) CommentFunc(fn func(*GoWriter)) {
	tmp := w.SubWriter()
	fn(tmp)
	w.Comment(tmp.Bytes())
}

func (w *GoWriter) SeparateN(n int) {
	for i := w.TrailingBlankLinesN(n); i < n; i++ {
		w.Newline()
	}
}

func (w *GoWriter) Separate() {
	w.SeparateN(2)
}

func (w *GoWriter) TrailingBlankLines() int {
	return trailingBlankLines(w.Bytes())
}

func (w *GoWriter) TrailingBlankLinesN(n int) int {
	return trailingBlankLinesN(w.Bytes(), n)
}
