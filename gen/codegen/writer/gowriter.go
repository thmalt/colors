func (w *GoWriter) LineComment(a ...any) {
	s := buildString(a...)
	w.lineComment(s)
}

func (w *GoWriter) LineCommentln(a ...any) {
	s := buildString(a...)
	w.lineComment(s)
	w.Writeln()
}
func (w *GoWriter) comment(s string) {
	if strings.ContainsAny(s, "\r\n") {
		if strings.Contains(s, "*/") {
			s = strings.ReplaceAll(s, "*/", "*\\/")
		}
	}

	w.Write("/* ", s, " */")
}

func (w *GoWriter) lineComment(s string) {
	if strings.ContainsAny(s, "\r\n") {
		if strings.Contains(s, "*/") {
			s = strings.ReplaceAll(s, "*/", "*\\/")
		}
		w.LineWriteln("/*")
		w.Write(s)
		w.LineWrite("*/")
	} else {
		w.LineWrite("//")
		if !strings.HasPrefix(s, "\t") {
			w.Write(' ')
		}
		w.Write(s)
	}
}

func buildString(a ...any) string {
	var w strings.Builder
	for _, arg := range a {
		switch v := arg.(type) {
		case string:
			w.WriteString(v)
		case byte:
			w.WriteByte(v)
		case rune:
			w.WriteRune(v)
		case []byte:
			w.Write(v)
		default:
			fmt.Fprint(&w, v)
		}
	}
	return w.String()
}

func isStdlib(path string) bool {
	before, _, _ := strings.Cut(path, "/")
	return !strings.Contains(before, ".")
}

func splitImports(imports []string) (stdlib []string, others []string) {
	for _, pkg := range imports {
		pkg = strings.TrimSpace(pkg)
		if pkg == "" {
			continue
		}

		if isStdlib(pkg) {
			stdlib = append(stdlib, pkg)
		} else {
			others = append(others, pkg)
		}
	}

	return
}
